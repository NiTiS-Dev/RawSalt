namespace RawSalt.Graphics.Rendering;

/// <summary>
/// Defines direction of front face.
/// </summary>
public enum FrontFace
{
	/// <summary>
	/// Front face's vertices located in counter-clock-wise order.
	/// </summary>
	CounterClockWise = 0,

	/// <summary>
	/// Front face's vertices located in clock-wise order.
	/// </summary>
	ClockWise = 1,
}